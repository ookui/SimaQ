// Runs inside the real app's main WKWebView against a disposable copy of Samples.
const sleep = ms => new Promise(resolve => setTimeout(resolve,ms));
const ok = (condition,message) => { if(!condition) throw Error(message); checks.push(message) };
const checks=[];
const wait = async (fn,message) => {for(let i=0;i<160;i++){if(fn())return;await sleep(30)} throw Error(message)};
const note = '公司/富瀚微.md', report = '报告/视觉 产业.html', pdf = '报告/访谈纪要.pdf';
const state = () => rpc('bootstrap');
const root = await state();
ok(root.root && root.root.length>0,'工作区已打开');
await SimaShell.event('openPath',{path:note,newTab:true});
await wait(()=>document.querySelector('.tab[aria-selected="true"]')?.title===note,'note did not open');
ok(!!document.querySelector('#hosts .doc-host'),'目录中的 Markdown 进入真实编辑器');
ok(!!document.querySelector('#hosts table'),'可视化管道表格已生成');
const initial = await rpc('read',{path:note});
await SimaShell.run('file.save');
ok((await rpc('read',{path:note})).version===initial.version,'无编辑存储不改变文件散列');
await SimaShell.run('search.workspace');
await wait(()=>document.querySelector('#queryInput'),'missing search field');
const search=document.querySelector('#queryInput');
search.value='physical ai';search.dispatchEvent(new Event('input',{bubbles:true}));
await wait(()=>[...document.querySelectorAll('.group-head')].some(n=>n.title.startsWith('归档/')),'missing archive search result');
const archive=[...document.querySelectorAll('.group-head')].find(n=>n.title.startsWith('归档/'));
const group=archive.closest('.search-file-group');
ok(+group.querySelector('.group-count').textContent === (await rpc('read',{path:archive.title})).text.match(/physical[ _\-‑]+ai/gi).length,'归档文件栏显示全部正文命中');
const second=group.querySelectorAll('.hit-row')[1];
ok(second.classList.contains('hit-row') && second.innerText.includes('Physical‑AI'),'同名归档笔记第二处命中 Unicode 连字符');
second.click();
await wait(()=>document.querySelector('.tab[aria-selected="true"]')?.title.startsWith('归档/'),'archive hit did not open');
ok(document.querySelectorAll('.tab').length>=2,'两个标签同时保留');
await SimaShell.event('openPath',{path:report,newTab:true});
await wait(()=>document.querySelector('.tab[aria-selected="true"]')?.title===report,'html tab did not open');
ok(await rpc('readerTrusted',{path:report})===false,'HTML 报告初始禁用脚本');
await SimaShell.event('openPath',{path:pdf,fragment:'page=2',newTab:true});
await wait(()=>document.querySelector('.tab[aria-selected="true"]')?.title===pdf,'pdf tab did not open');
await sleep(180);
ok((await rpc('readerState')).page===2,'PDFKit 定位到第二页');
await SimaShell.run('navigate.back');
await wait(()=>document.querySelector('.tab[aria-selected="true"]')?.title===report,'history did not restore HTML');
ok(true,'后退回到 HTML 报告');
await SimaShell.event('openPath',{path:note,newTab:true});
await SimaShell.run('app.settings');await sleep(100);
ok(!!document.querySelector('[role=dialog]'),'设置对话框已打开');
document.querySelector('[role=dialog]').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
await sleep(100);
ok(await SimaShell.prepareClose()!==false,'关闭前保存会话');
const saved=(await state()).session;
ok(saved.tabs.some(tab=>tab.path===note) && saved.tabs.some(tab=>tab.path===pdf),'标签页与状态已保存');
return {checks,archive:archive.title,active:saved.active,tabs:saved.tabs.map(t=>t.path)};
