// Runs inside the real app's main WKWebView against a disposable copy of Samples.
const sleep = ms => new Promise(resolve => setTimeout(resolve,ms));
const ok = (condition,message) => { if(!condition) throw Error(message); checks.push(message) };
const checks=[];
const wait = async (fn,message) => {for(let i=0;i<160;i++){if(fn())return;await sleep(30)} throw Error(message)};
const note = '公司/富瀚微.md', report = '报告/视觉 产业.html', pdf = '报告/访谈纪要.pdf';
const state = () => rpc('bootstrap');
const root = await state();
ok(root.root && root.root.length>0,'工作区已打开');
const treeRow = path => [...document.querySelectorAll('.tree-row')].find(row=>row.dataset.path===path);
const expand = path => { if(treeRow(path)?.getAttribute('aria-expanded')==='false') treeRow(path).click(); };
const activePath = () => document.querySelector('.tab[aria-selected="true"]')?.title;
const tabCount = () => document.querySelectorAll('.tab').length;
expand('专题');
const topic = '专题/长文与标题定位.md';
treeRow(topic).click();
await wait(()=>activePath()===topic,'未打开专题笔记');
expand('公司');
const countBeforeReplace = tabCount();
treeRow(note).click();
await wait(()=>activePath()===note && tabCount()===countBeforeReplace,'普通点击未复用标签');
expand('专题');
treeRow(topic).dispatchEvent(new MouseEvent('click',{metaKey:true,bubbles:true}));
await wait(()=>activePath()===topic && tabCount()===countBeforeReplace+1,'⌘ 点击未保留原标签');
expand('报告');
treeRow(report).dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true}));
const newTabLabel = SimaSettings.menuText('在新标签页中打开');
[...document.querySelectorAll('[role="menuitem"]')].find(item=>item.textContent===newTabLabel).click();
await wait(()=>activePath()===report && tabCount()===countBeforeReplace+2,'右键菜单未打开新标签');
ok(true,'左侧目录支持替换当前标签、⌘ 点击和右键新标签');
await SimaShell.event('openPath',{path:note,newTab:true});
await wait(()=>document.querySelector('.tab[aria-selected="true"]')?.title===note,'note did not open');
ok(!!document.querySelector('#hosts .doc-host'),'目录中的 Markdown 进入真实编辑器');
ok(!!document.querySelector('#hosts table'),'可视化管道表格已生成');
const visibleHost = document.querySelector('#hosts .doc-host:not([hidden])');
const header = visibleHost.querySelector('.sima-page-header');
const metadata = header?.querySelector('.md-meta-block');
ok(metadata?.hidden && getComputedStyle(metadata).fontStyle === 'italic' &&
   header.querySelector('h1').textContent === '富瀚微','页首的斜体 YAML 默认收起');
ok(header.querySelector('.sima-folder-tag')?.textContent === '# 公司','标题下显示直接父目录标签');
const viewport = visibleHost.querySelector('.sima-editor');
const surface = getComputedStyle(header,'::before');
ok(Math.abs(parseFloat(surface.width) - viewport.clientWidth) <= 1 && surface.borderBottomWidth === '1px',
   '页首背景和底部分隔线横跨整个编辑栏');
const folderRow = document.querySelector('.tree-row[data-path="公司"]');
ok(folderRow && getComputedStyle(folderRow).getPropertyValue('--directory-accent') ===
   getComputedStyle(header).getPropertyValue('--directory-accent'),'目录图标和笔记页首共用主题色');
await wait(()=>document.querySelectorAll('#outlineList .outline-row').length > 1,'大纲未显示');
ok(!visibleHost.querySelector('.sima-fold') && document.querySelectorAll('#outlineList .outline-row').length > 1,
   '章节全部展开，右侧保留多级大纲');
const lastOutlineRow = document.querySelector('#outlineList .outline-row:last-child');
lastOutlineRow.click();
await wait(()=>lastOutlineRow.getAttribute('aria-current') === 'location','点击大纲未定位章节');
ok(viewport.scrollTop > 0,'点击右侧大纲滚动到对应章节');
const initial = await rpc('read',{path:note});
await SimaShell.run('file.save');
ok((await rpc('read',{path:note})).version===initial.version,'无编辑存储不改变文件散列');
await SimaShell.run('search.workspace');
await wait(()=>document.querySelector('#queryInput'),'missing search field');
const variantInput=document.querySelector('#queryInput');
variantInput.value='視覺感知';variantInput.dispatchEvent(new Event('input',{bubbles:true}));
const variantHit=()=>[...document.querySelectorAll('.hit-row')].find(row=>
  row.title.startsWith(note+'\n') && row.querySelector('mark')?.textContent==='视觉感知');
await wait(variantHit,'繁体查询未显示简体原文');
variantHit().click();
await wait(()=>visibleHost.querySelector('mark.md-search-select')?.textContent==='视觉感知','简繁搜索未定位到原文字形');
ok(true,'繁体查询可点击并高亮简体原文');
const searchHead=()=>[...document.querySelectorAll('.group-head')].find(h=>h.title===note);
viewport.scrollTop=viewport.scrollHeight;
ok(viewport.scrollTop>0,'搜索页首定位前已滚动正文');
searchHead().querySelector('.group-open').click();
await wait(()=>viewport.scrollTop===0 && !visibleHost.querySelector('mark.md-search-select'),'搜索标题未返回文首');
ok(searchHead().querySelector('.expander').getAttribute('aria-expanded')==='true','点击标题保留命中列表');
searchHead().querySelector('.expander').click();
ok(searchHead().querySelector('.expander').getAttribute('aria-expanded')==='false','箭头仍可独立折叠');
searchHead().querySelector('.group-open').click();
await sleep(80);
ok(searchHead().querySelector('.expander').getAttribute('aria-expanded')==='false','打开已折叠标题保持折叠');
const search=document.querySelector('#queryInput');
search.value='physical ai';search.dispatchEvent(new Event('input',{bubbles:true}));
await wait(()=>[...document.querySelectorAll('.group-head')].some(n=>n.title.startsWith('归档/')),'missing archive search result');
const archive=[...document.querySelectorAll('.group-head')].find(n=>n.title.startsWith('归档/'));
const group=archive.closest('.search-file-group');
ok(+group.querySelector('.group-count').textContent === (await rpc('read',{path:archive.title})).text.match(/physical[ _\-‑]+ai/gi).length,'归档文件栏显示全部正文命中');
const second=group.querySelectorAll('.hit-row')[1];
ok(second.classList.contains('hit-row') && second.innerText.includes('Physical‑AI'),'同名归档笔记第二处命中 Unicode 连字符');
second.dispatchEvent(new MouseEvent('click',{bubbles:true,metaKey:true}));
await wait(()=>document.querySelector('.tab[aria-selected="true"]')?.title.startsWith('归档/'),'archive hit did not open');
const archiveHeader = document.querySelector('#hosts .doc-host:not([hidden]) .sima-page-header');
ok(archiveHeader?.querySelector('.sima-folder-tag')?.textContent === '# 2025','多层目录使用最内层目录名');
ok(archiveHeader && getComputedStyle(archiveHeader).getPropertyValue('--directory-accent') !==
   getComputedStyle(header).getPropertyValue('--directory-accent'),'多级子目录的笔记采用所属大目录的独立配色');
ok(document.querySelectorAll('.tab').length>=2,'两个标签同时保留');
const trashLabel = SimaSettings.menuText('移入废纸篓…');
const chooseTrash = async () => {
  [...document.querySelectorAll('[role="menuitem"]')].find(item => item.textContent === trashLabel).click();
  await wait(() => document.querySelector('[data-answer="trash"]'), '未显示废纸篓确认框');
};
const resultGroup = () => [...document.querySelectorAll('.group-head')].find(row => row.title === archive.title);
for (const row of [resultGroup(), resultGroup().parentElement.querySelector('.hit-row'), document.querySelector('.tab[aria-selected="true"]')]) {
  row.dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true}));
  await chooseTrash();
  ok(document.querySelector('.dialog-content p').textContent === archive.title,'删除确认显示归档笔记的完整相对路径');
  document.querySelector('[data-answer="cancel"]').click();
}
ok(activePath() === archive.title && resultGroup(), '取消删除保留原标签与搜索结果');
document.getElementById('documentMenu').click();
await chooseTrash();
document.querySelector('[data-answer="trash"]').click();
await wait(() => !resultGroup() && ![...document.querySelectorAll('.tab')].some(t => t.title === archive.title),
  '删除后搜索结果或标签未清理');
const paths = (await rpc('files')).map(file => file.path);
ok(!paths.includes(archive.title) && paths.includes(note),'在文档菜单删除搜索打开的归档笔记，保留其他目录的同名笔记');
const indexed = await rpc('search',{q:'physical ai'});
ok(!indexed.some(row => row.path === archive.title) && indexed.some(row => row.path === note), '搜索索引同步移除已删除页面');
await SimaShell.event('openPath',{path:report,newTab:true});
await wait(()=>document.querySelector('.tab[aria-selected="true"]')?.title===report,'html tab did not open');
ok(await rpc('readerTrusted',{path:report})===false,'HTML 报告初始禁用脚本');
await SimaShell.event('openPath',{path:pdf,fragment:'page=2',newTab:true});
await wait(()=>document.querySelector('.tab[aria-selected="true"]')?.title===pdf,'pdf tab did not open');
await sleep(180);
ok((await rpc('readerState')).page===2,'PDFKit 定位到第二页');
await SimaShell.run('navigate.back');
await wait(()=>document.querySelector('.tab[aria-selected="true"]')?.title===report,'history did not restore HTML');
ok(true,'后退回到 HTML 报告');
await SimaShell.event('openPath',{path:note,newTab:true});
await SimaShell.run('app.settings');await sleep(100);
ok(!!document.querySelector('[role=dialog]'),'设置对话框已打开');
document.querySelector('[role=dialog]').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
await sleep(100);
ok(await SimaShell.prepareClose()!==false,'关闭前保存会话');
const saved=(await state()).session;
ok(saved.tabs.some(tab=>tab.path===note) && saved.tabs.some(tab=>tab.path===pdf),'标签页与状态已保存');
return {checks,archive:archive.title,active:saved.active,tabs:saved.tabs.map(t=>t.path)};
