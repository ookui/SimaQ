// Run in the workspace shell with its command registry, canvas and navigation history.
const checks=[];
const check=(ok,message)=>{if(!ok)throw Error(message);checks.push(message);};
const paint=()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));
async function wait(test) {
  for (let i=0;i<200;i++) { if (test()) return; await new Promise(r=>setTimeout(r,20)); }
  throw Error('Timed out: '+test);
}
const {root}=await rpc('bootstrap'), data=await rpc('workspaceGraph',{root});
const target='专题/长文与标题定位.md', source='公司/富瀚微.md';
const find=path=>data.nodes.findIndex(n=>n.path===path);
check(data.edges.some(([a,b])=>a===find(source) && b===find(target)),'indexed markdown link resolves');
const nav=document.querySelector('.side-switch');
check(nav.lastElementChild.id==='graphButton','Graph follows Files and Search');
nav.lastElementChild.click();
const panel=()=>document.querySelector('.workspace-graph:not([hidden])');
await wait(()=>panel()?.querySelector('.graph-counts').textContent);
check(panel().parentElement.id==='stage' && nav.lastElementChild.getAttribute('aria-pressed')==='true','Graph is the active workspace page');
const canvas=panel().querySelector('canvas'), ctx=canvas.getContext('2d');
const circle=ctx.arc.bind(ctx), fill=ctx.fill.bind(ctx), clear=ctx.clearRect.bind(ctx), stroke=ctx.stroke.bind(ctx);
let current,dots=[],strokes=[];
ctx.clearRect=(...args)=>{dots=[];strokes=[];clear(...args);};
ctx.arc=(x,y,r,...args)=>{current={x,y,r,alpha:ctx.globalAlpha};circle(x,y,r,...args);};
ctx.fill=(...args)=>{dots.push(current);fill(...args);};
ctx.stroke=(...args)=>{strokes.push(ctx.globalAlpha);stroke(...args);};
const fit=()=>panel().querySelector('[data-zoom="fit"]').click();
fit(); await paint();
check(dots.length===data.nodes.length,'fit displays every node');
const degree=data.nodes.map(()=>0);
for(const [a,b] of data.edges){degree[a]++;degree[b]++;}
const i=find(source), j=find(target);
const area=d=>1+5*d/(d+6);
check(Math.abs((dots[i].r/dots[j].r)**2-area(degree[i])/area(degree[j]))<.001,'screen areas use bounded total degree');
const bounds=canvas.getBoundingClientRect();
const point=n=>({clientX:bounds.left+n.x,clientY:bounds.top+n.y,bubbles:true,button:0,pointerId:1});
const dispatch=(name,coords)=>canvas.dispatchEvent(new PointerEvent(name,coords));
canvas.setPointerCapture=()=>{};
let at=point(dots[j]);
dispatch('pointermove',at); await paint();
check(!panel().querySelector('.graph-tip').hidden && panel().querySelector('.graph-tip strong').textContent===data.nodes[j].title,'hover shows full title');
check(dots[i].alpha===1 && dots.some(n=>n.alpha<.3) && strokes.some(a=>a>.9) && strokes.some(a=>a<.2),'hover highlights adjacent nodes and edges');
const neighborBefore={...dots[i]};
dispatch('pointerdown',at);
dispatch('pointermove',{...at,clientX:at.clientX+54,clientY:at.clientY+20});
await paint();
check(Math.abs(dots[j].x-(at.clientX-bounds.left+54))<1,'dragged node follows pointer');
check(Math.hypot(dots[i].x-neighborBefore.x,dots[i].y-neighborBefore.y)>.1,'a linked neighbor moves during drag');
dispatch('pointerup',at); await paint();
dispatch('pointerleave',at);
fit(); await paint();
at=point(dots[j]);
dispatch('pointerdown',at);dispatch('pointerup',at);await paint();
const wheel=dy=>canvas.dispatchEvent(new WheelEvent('wheel',{...at,buttons:2,deltaY:dy,cancelable:true}));
const scale=()=>parseInt(panel().querySelector('.graph-scale').textContent);
wheel(-180);await paint();check(scale()>100,'right-button wheel zooms in');
for(let k=0;k<5;k++) {wheel(-180);await paint();}
const maxDot=Math.max(...dots.map(d=>d.r));
check(maxDot<=24.0001,'zoomed node radius stays within 24 CSS pixels');
fit();await paint();
at=point(dots[j]);wheel(-100);await paint();
const savedZoom=scale();
canvas.dispatchEvent(new MouseEvent('dblclick',at));
await wait(()=>!panel() && document.querySelector('.tab[aria-selected=true]')?.title===target);
const key=(value,code)=>document.body.dispatchEvent(new KeyboardEvent('keydown',{key:value,code,metaKey:true,bubbles:true,cancelable:true}));
key('[','BracketLeft');
await wait(()=>panel() && scale()===savedZoom);
check(nav.lastElementChild.getAttribute('aria-pressed')==='true','Command+[ restores graph page and zoom');
await paint();
check(dots.some(n=>n.alpha<.3),'history restores the selected neighborhood');
key(']','BracketRight');
await wait(()=>!panel() && document.querySelector('.tab[aria-selected=true]')?.title===target);
check(true,'Command+] returns to the document');
await SimaShell.run('view.graph');
const originalPrefs=!!SimaSettings.settings.graphJournals;
await SimaSettings.execute('view.graphJournals');
check((await rpc('getPrefs')).graphJournals===!originalPrefs,'journal menu persists preference');
await SimaSettings.execute('view.graphJournals');
panel().querySelector('[data-dismiss]').click();
await wait(()=>!panel());
check(true,'closing graph returns to document');
return {checks};
